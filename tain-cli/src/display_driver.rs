//! Installing and removing the virtual display driver.
//!
//! # Why Tain ships a driver rather than using whichever one is there
//!
//! An indirect display driver registers a display *adapter* per monitor it can
//! present, and those adapters exist from the moment it is installed. They are
//! useless until the driver is told to present a monitor behind one — see
//! [`tain_core::virtual_display`], which found sixteen of them on a machine with
//! Parsec's driver and could attach none of them.
//!
//! Telling a driver to present a monitor is the driver's own business, and each
//! does it differently: a companion service, a private control channel, a
//! settings file read when the device is enabled. Parsec's is driven by Parsec.
//! So the only virtual display Tain can actually create is one belonging to a
//! driver Tain knows how to talk to, which means shipping one.
//!
//! Everything after that — putting it on the desktop, sizing it, taking it away
//! — is the same for all of them and lives in `virtual_display`.
//!
//! # Opt-in, and separately from the service
//!
//! Installing a driver is a bigger ask than installing a service: Windows shows
//! its own publisher dialog, the decision is remembered for that publisher, and
//! a driver is a thing people are right to be careful about. So nothing here
//! happens on its own — the settings panel offers it, and a host with no
//! virtual display driver works exactly as it does today, minus the feature.
//!
//! This mirrors [`super::service`] deliberately, down to the elevation dance:
//! the unprivileged app relaunches itself under `runas` with a flag, which is
//! the only way to get administrator rights, and doing it the same way twice
//! beats two half-remembered variants.
//!
//! # How this driver is told to present a monitor
//!
//! Read out of `MttVDD.dll` rather than from documentation, because there is
//! none. It hosts a named pipe — `\\.\pipe\MTTVirtualDisplayPipe`, built with
//! `CreateNamedPipeW` — and answers a small set of verbs:
//!
//! - `SETDISPLAYCOUNT` is the one that matters. Its log line is *"Display Count
//!   Changed, Restarting Driver"*, so asking for a count is how a monitor comes
//!   to exist: the driver writes the number into its settings file and restarts
//!   itself. No device disable/enable of ours, and nothing needing
//!   administrator rights after the install.
//!
//!   It is not how one stops existing. The driver refuses a count of zero and
//!   substitutes one, and any change to the count restarts it — so every
//!   monitor it presents goes away and comes back, and Windows may attach what
//!   comes back. Removal is therefore taking the display off the desktop, which
//!   is [`tain_core::virtual_display::detach`] and no business of the driver's.
//!   See [`remove_display`].
//! - `PING`, `GETSETTINGS`, `RELOAD_DRIVER` for state and lifecycle.
//! - `GETALLGPUS`, `GETASSIGNEDGPU`, `VDDPATH` for which adapter it renders on
//!   and where its settings live.
//! - The rest set options this project has no reason to touch —
//!   `HARDWARECURSOR`, `HDRPLUS`, `CUSTOMEDID`, `PREVENTSPOOF`, `LOGGING`.
//!
//! Its settings are `vdd_settings.xml`, in a folder named by
//! `HKLM\SOFTWARE\MikeTheTech\VirtualDisplayDriver\VDDPATH` — falling back to
//! `C:\VirtualDisplayDriver` when that is unset. Installing points it at
//! `%ProgramData%\Tain\VirtualDisplay` instead, which is where machine-wide
//! application data belongs, and only when nothing has already chosen: see
//! [`decide_settings_path`]. `<monitors><count>` is what `SETDISPLAYCOUNT`
//! writes; `<resolutions>` is the mode list each presented monitor offers.
//!
//! Which means the two halves of the feature meet cleanly: this module gets the
//! driver installed and a monitor presented, and everything after that — onto
//! the desktop, at a size, and away again — is
//! [`tain_core::virtual_display`], which needs no driver of any particular kind.

/// Argument that makes this executable install the driver and exit.
pub const INSTALL_FLAG: &str = "--install-display-driver";

/// The same, for removal.
pub const UNINSTALL_FLAG: &str = "--uninstall-display-driver";

/// The driver package, carried inside this executable.
///
/// Generated by `build.rs` from `third_party/VirtualDisplayDriver`, and empty
/// when nothing has been vendored there — a source tree that has not run the
/// fetch script builds a Tain that says it ships no driver, which is the same
/// arrangement ffmpeg has.
mod embedded {
    include!(concat!(env!("OUT_DIR"), "/display_driver_package.rs"));
}

/// Where the package is written out to be installed from.
///
/// # Why it is unpacked at all rather than shipped as a folder
///
/// It was going to be a folder beside the executable, and that was wrong. Ask
/// somebody to extract a driver package into a particular directory and the
/// only people who can are the people who could have run the driver's own
/// installer instead — a feature that works only for those who did not need it.
///
/// So the package rides inside the binary and is written out here when the
/// install button is pressed. Tain stays one file and there is nothing to put
/// anywhere. `tain_core::ffmpeg_runtime` does the same with 66 MB of DLLs; this
/// is 132 KB.
///
/// Under the user's local application data rather than the temp directory:
/// `UpdateDriverForPlugAndPlayDevices` copies the package into the driver store
/// itself, so nothing here is needed afterwards — but a path that survives a
/// failed install is a path somebody can be asked to look at.
fn staging_dir() -> Option<std::path::PathBuf> {
    Some(std::path::PathBuf::from(std::env::var("LOCALAPPDATA").ok()?).join("Tain/driver"))
}

/// Where a package put there by hand overrides the embedded one.
///
/// For trying a newer driver, or a different one, without a rebuild. Not the
/// path anybody is expected to use — see `staging_dir` — which is why nothing
/// in the interface mentions it.
pub const PACKAGE_DIR: &str = "drivers/virtual-display";

/// What the shipped `.inf` says it installs.
///
/// # Why these are read rather than chosen
///
/// They were constants, named after Tain, and that would not have worked. A
/// driver package's `.cat` catalog holds a signed hash of every file in it,
/// the `.inf` included — so the package installs *byte for byte* or not at
/// all. Renaming the device to something of ours voids the signature, and a
/// voided signature is not a cosmetic problem: Windows refuses the package, or
/// demands the machine be put into test-signing mode, which is not a thing to
/// ask of somebody who wanted a second monitor.
///
/// So the package is shipped exactly as its authors signed it, and this reads
/// out of it what has to be handed to the device APIs. Which also means a
/// different package can be dropped in without editing any of this.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Package {
    /// The `.inf` itself, which is what `newdev` is pointed at.
    pub inf: std::path::PathBuf,
    /// `ClassGuid` from `[Version]`, as text. The class the device is created
    /// in has to be the one the driver expects to be installed into.
    pub class: String,
    /// The `Root\…` id the `.inf` claims, e.g. `Root\MttVDD`.
    pub hardware_id: String,
    /// What Windows will call the device, for the settings panel to repeat.
    pub device_name: Option<String>,
    /// Whether this came out of the executable rather than off disk.
    ///
    /// Decides whether installing has to write the files out first. Not part of
    /// what an `.inf` says, so [`parse_inf`] leaves it false and whoever found
    /// the package sets it.
    pub embedded: bool,
}

/// Pull out of an `.inf` the three things installing it needs.
///
/// Deliberately not a general INF parser. The format has directives, include
/// files, architecture-decorated sections and string substitution, and none of
/// that is needed to answer "what class, what id, what is it called" — while a
/// parser that tried would be a great deal of code to be subtly wrong in.
///
/// Pure, so the shape of a real `.inf` can be pinned in a test rather than
/// discovered on somebody's machine at install time.
pub fn parse_inf(text: &str) -> Option<Package> {
    let mut class = None;
    let mut hardware_id = None;
    let mut device_name = None;

    for line in text.lines() {
        // Comments run to end of line and can follow a value.
        let line = line.split(';').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }

        if let Some((key, value)) = line.split_once('=') {
            let key = key.trim();
            let value = value.trim();
            if key.eq_ignore_ascii_case("ClassGuid") && class.is_none() {
                // `[Version]` can carry several directives on one line,
                // comma-separated, so the value stops at the first comma.
                class = Some(
                    value.split(',').next().unwrap_or(value).trim().to_string(),
                );
            }
            if key.eq_ignore_ascii_case("DeviceName") && device_name.is_none() {
                device_name = Some(value.trim_matches('"').to_string());
            }
        }

        // The hardware id is not a key: it is the last field of a device entry,
        // `%DeviceName% = Install_Section, Root\Something`. Finding it by shape
        // rather than by section avoids having to know which of the
        // architecture-decorated `[Standard.NT…]` sections this build uses.
        if hardware_id.is_none()
            && let Some(found) = line
                .split(',')
                .map(str::trim)
                .find(|part| part.len() > 5 && part[..5].eq_ignore_ascii_case("root\\"))
        {
            hardware_id = Some(found.to_string());
        }
    }

    Some(Package {
        inf: std::path::PathBuf::new(),
        class: class?,
        hardware_id: hardware_id?,
        device_name,
        embedded: false,
    })
}

/// What to do about the folder the driver reads its settings from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SettingsPath {
    /// Somebody has already said where it goes. Use that, change nothing.
    Keep(std::path::PathBuf),
    /// Nothing has said, so Tain chooses and records it.
    Claim(std::path::PathBuf),
}

/// Whether Tain gets to choose where the driver keeps its settings.
///
/// # Why an existing setting is never repointed
///
/// `HKLM\SOFTWARE\MikeTheTech\VirtualDisplayDriver\VDDPATH` belongs to the
/// driver, not to Tain. A machine can already have this driver installed by its
/// own installer, with a settings file somebody has edited — a resolution list,
/// an HDR option, a GPU choice. Moving the pointer would orphan all of it in
/// silence, and the person it happened to would have no reason to look here.
///
/// So only the *absence* of a setting is taken as permission to choose one.
pub fn decide_settings_path(
    configured: Option<std::path::PathBuf>,
    ours: std::path::PathBuf,
) -> SettingsPath {
    match configured {
        Some(existing) if !existing.as_os_str().is_empty() => SettingsPath::Keep(existing),
        _ => SettingsPath::Claim(ours),
    }
}

/// Whether uninstalling may clear the pointer.
///
/// Only when it is still the one Tain wrote. Anything else was somebody
/// else's decision, and removing it would break a driver Tain did not install
/// — an uninstall that reaches outside what it installed is worse than one
/// that leaves a registry value behind.
pub fn may_forget_settings_path(
    configured: Option<std::path::PathBuf>,
    ours: &std::path::Path,
) -> bool {
    configured.is_some_and(|existing| existing == ours)
}

/// Whether the driver is installed, and whether it can be used.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum DriverState {
    /// Installed, and presenting at least one monitor Tain can attach.
    Ready,
    /// Installed, but no monitor is present behind any of its adapters.
    ///
    /// The driver is there and Windows has bound it; it simply has not been
    /// asked to present anything. Distinguished from [`Self::NotInstalled`]
    /// because the fix is different and neither one is an error.
    Idle,
    /// Not installed on this machine.
    #[default]
    NotInstalled,
    /// Nothing to install: this build ships no driver package.
    ///
    /// A source build, or a copy where the `drivers` folder did not travel.
    /// Said plainly rather than shown as a failed install, because there is
    /// nothing the person clicking can do about it.
    NotBundled,
}

impl DriverState {
    /// Whether a virtual display can be created right now.
    pub fn is_usable(self) -> bool {
        self == Self::Ready
    }

    /// Whether the driver is on this machine at all.
    pub fn is_installed(self) -> bool {
        matches!(self, Self::Ready | Self::Idle)
    }

    /// One line for the settings panel.
    pub fn summary(self) -> &'static str {
        match self {
            Self::Ready => "Installed. A virtual display can be created.",
            Self::Idle => "Installed, but no virtual monitor is present yet.",
            Self::NotInstalled => "Not installed. Virtual displays need it.",
            Self::NotBundled => "This copy of Tain ships no driver to install.",
        }
    }
}

#[cfg(target_os = "windows")]
mod windows_impl {
    use super::*;
    use anyhow::{bail, Context, Result};

    /// The driver package this build ships, if it ships one.
    ///
    /// Looks for exactly one `.inf` so that adding the package is a matter of
    /// dropping a folder in rather than also editing a name in here — and so
    /// that a folder containing something else entirely is reported as absent
    /// rather than half-found.
    /// The package to install, wherever it comes from.
    ///
    /// A folder beside the executable wins if one is there, so a newer driver
    /// can be tried without a rebuild; otherwise the embedded one, which is
    /// what everybody actually gets.
    pub fn package() -> Option<Package> {
        beside_the_exe().or_else(embedded_package)
    }

    /// The embedded package, described without unpacking it.
    ///
    /// The `.inf` is read out of the binary rather than off disk, so the state
    /// shown in Settings costs nothing and needs no directory to exist. Writing
    /// the files out is [`unpack`], and only installing does that.
    fn embedded_package() -> Option<Package> {
        let (name, bytes) = embedded::FILES
            .iter()
            .find(|(name, _)| name.to_ascii_lowercase().ends_with(".inf"))?;
        let mut found = parse_inf(&decode(bytes)).or_else(|| {
            tracing::warn!("the embedded {name} does not name a class and a Root\\ device");
            None
        })?;
        // Filled in by `unpack`; nothing reads it until then.
        found.inf = std::path::PathBuf::from(*name);
        found.embedded = true;
        Some(found)
    }

    /// Write the embedded package out so Windows can be pointed at it.
    ///
    /// Every file together in one directory, because the `.cat` signs the
    /// others and Windows looks for it beside the `.inf`. Cleared first: a
    /// leftover file from a previous, different package would be checked
    /// against a catalog that does not describe it.
    fn unpack() -> Result<std::path::PathBuf> {
        let dir = staging_dir().context("no local application data directory")?;
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir)
            .with_context(|| format!("could not create {}", dir.display()))?;
        for (name, bytes) in embedded::FILES {
            let path = dir.join(name);
            std::fs::write(&path, bytes)
                .with_context(|| format!("could not write {}", path.display()))?;
        }
        Ok(dir)
    }

    fn beside_the_exe() -> Option<Package> {
        let beside = std::env::current_exe().ok()?.parent()?.join(PACKAGE_DIR);
        let mut infs = std::fs::read_dir(&beside)
            .ok()?
            .filter_map(|entry| entry.ok())
            .map(|entry| entry.path())
            .filter(|path| {
                path.extension().is_some_and(|ext| ext.eq_ignore_ascii_case("inf"))
            });
        let inf = infs.next()?;
        if infs.next().is_some() {
            tracing::warn!(
                "{} holds more than one .inf — not guessing which is the driver",
                beside.display()
            );
            return None;
        }

        // Read as bytes and lossily decoded: an `.inf` may be UTF-16 with a
        // BOM, ANSI, or UTF-8, and refusing one for its encoding would be a
        // strange way to fail to install a driver.
        let bytes = std::fs::read(&inf).ok()?;
        let text = decode(&bytes);
        let mut found = parse_inf(&text).or_else(|| {
            tracing::warn!("{} does not name a class and a Root\\ device", inf.display());
            None
        })?;
        found.inf = inf;
        Some(found)
    }

    /// Bytes to text, whatever the file was written in.
    fn decode(bytes: &[u8]) -> String {
        match bytes {
            [0xFF, 0xFE, rest @ ..] => {
                let words: Vec<u16> = rest
                    .chunks_exact(2)
                    .map(|pair| u16::from_le_bytes([pair[0], pair[1]]))
                    .collect();
                String::from_utf16_lossy(&words)
            }
            _ => String::from_utf8_lossy(bytes).into_owned(),
        }
    }

    /// Whether Windows has this driver's device installed.
    ///
    /// Asked by name against the package's own device name rather than against
    /// anything of ours: the driver is shipped as its authors signed it, so
    /// what appears in the display list is *their* name — "Virtual Display
    /// Driver", by Mike The Tech, for the package this ships today. Looking for
    /// "Tain" would have found nothing, ever.
    /// The virtual displays belonging to *this* driver, and no other.
    ///
    /// # Why everything here is scoped and not just the risky parts
    ///
    /// [`tain_core::virtual_display::available`] answers a broader question —
    /// every adapter on the machine that looks like a virtual display, whoever
    /// installed it. That is the right question for the module that drives one,
    /// and the wrong one for every caller in here: a machine with Parsec
    /// installed has sixteen of its adapters enumerating alongside this
    /// driver's, and "remove the last one" reaching Parsec's display would take
    /// away a screen Tain has no business touching.
    ///
    /// Matched on the adapter name the package declares, because that is what
    /// Windows shows: the driver is installed exactly as its authors signed it,
    /// so the name in the display list is theirs. Looking for "Tain" would find
    /// nothing, ever — which is the same mistake the hardware id made once
    /// already.
    fn ours(package: Option<&Package>) -> Vec<tain_core::virtual_display::VirtualDisplay> {
        let wanted = package
            .and_then(|p| p.device_name.as_deref())
            .unwrap_or("virtual display driver")
            .to_ascii_lowercase();
        tain_core::virtual_display::available()
            .into_iter()
            .filter(|screen| screen.adapter.to_ascii_lowercase().contains(&wanted))
            .collect()
    }

    /// What the settings panel shows.
    pub fn state() -> DriverState {
        let package = package();
        let screens = ours(package.as_ref());
        if !screens.is_empty() {
            let ready = screens.iter().any(|screen| screen.ready);
            return if ready { DriverState::Ready } else { DriverState::Idle };
        }
        if package.is_none() {
            return DriverState::NotBundled;
        }
        DriverState::NotInstalled
    }

    /// Whether the driver on this machine is the one Tain put here.
    ///
    /// # Why this question is asked before anything is taken away
    ///
    /// The clean-up below removes virtual displays nobody is using any more,
    /// and it has to be sure they are Tain's to remove. This driver can also
    /// arrive by its own installer, from its own authors, on a machine where
    /// somebody uses it as a permanent second screen — and reaping *that* every
    /// time Tain is not running would be taking away a monitor on the strength
    /// of having recognised the name of its driver.
    ///
    /// The settings pointer answers it exactly. [`decide_settings_path`] claims
    /// `HKLM\…\VDDPATH` only when nothing else has set it, and leaves an
    /// existing one alone — so the value reading back as Tain's folder means
    /// Tain installed this driver, and anything else means somebody got there
    /// first.
    pub fn installed_by_tain() -> bool {
        let (Some(configured), Some(ours)) = (settings::configured(), settings::ours()) else {
            return false;
        };
        configured == ours
    }

    /// Ask for elevation and install the driver.
    ///
    /// Relaunches this executable with the install flag under the `runas` verb.
    /// Installing a driver needs administrator rights and the app does not have
    /// them, so the prompt is unavoidable; expecting it beats being surprised.
    ///
    /// Windows will ask a second time, on its own, about trusting the
    /// publisher — that dialog belongs to Windows and cannot be suppressed,
    /// which is the point of it.
    pub fn request_install() -> Result<()> {
        if package().is_none() {
            bail!("this build of Tain ships no virtual display driver to install");
        }
        super::super::service::elevate_with(INSTALL_FLAG)
    }

    /// The same, for removal.
    pub fn request_uninstall() -> Result<()> {
        super::super::service::elevate_with(UNINSTALL_FLAG)
    }

    /// Where the driver keeps its settings, and how it is told to look there.
    ///
    /// # Why not the path the driver defaults to
    ///
    /// It defaults to `C:\VirtualDisplayDriver`, a folder in the root of the
    /// system drive. Its own source says so:
    ///
    /// ```text
    /// RegOpenKeyExW(HKEY_LOCAL_MACHINE, L"SOFTWARE\\MikeTheTech\\VirtualDisplayDriver", 0, KEY_READ, &hKey)
    /// RegQueryValueExW(hKey, L"VDDPATH", NULL, NULL, (LPBYTE)szPath, &dwBufferSize)
    /// wstring confpath = L"C:\\VirtualDisplayDriver";
    /// wstring settingsname = confpath + L"\\vdd_settings.xml";
    /// ```
    ///
    /// `ProgramData` is where machine-wide application data belongs, and this
    /// is exactly that: the driver runs in `WUDFHost.exe` under a service
    /// account, so there is no user profile in scope, and a virtual monitor has
    /// to exist at the sign-in screen when nobody is logged in. Which is also
    /// the answer to why it is not under `AppData`.
    ///
    /// # Why the settings have to be written at all
    ///
    /// Installing the driver registers adapters and nothing else. The file is
    /// read at every driver start, and `SETDISPLAYCOUNT` writes the count back
    /// into it — "Failed to update display count setting in XML. Restarting
    /// anyway" is what the driver logs when it cannot, which is a monitor count
    /// that survives until the next restart and no longer. That is why the
    /// package ships a `vdd_settings.xml`: it is not documentation.
    mod settings {
        use anyhow::{Context, Result};
        use std::path::PathBuf;
        use windows::core::PCWSTR;
        use windows::Win32::Foundation::ERROR_SUCCESS;
        use windows::Win32::System::Registry::{
            RegCloseKey, RegCreateKeyExW, RegDeleteValueW, RegOpenKeyExW, RegQueryValueExW,
            RegSetValueExW, HKEY, HKEY_LOCAL_MACHINE, KEY_READ, KEY_WRITE,
            REG_OPTION_NON_VOLATILE, REG_SZ,
        };

        /// The driver's own key, and the value naming its settings folder.
        const KEY: &str = r"SOFTWARE\MikeTheTech\VirtualDisplayDriver";
        const VALUE: &str = "VDDPATH";

        fn wide(s: &str) -> Vec<u16> {
            s.encode_utf16().chain(std::iter::once(0)).collect()
        }

        /// Where Tain would like the driver to keep its settings.
        pub fn ours() -> Option<PathBuf> {
            Some(PathBuf::from(std::env::var("ProgramData").ok()?).join("Tain/VirtualDisplay"))
        }

        /// What the driver will actually read, or `None` for its own default.
        pub fn configured() -> Option<PathBuf> {
            let key = wide(KEY);
            let value = wide(VALUE);
            let mut handle = HKEY::default();
            // SAFETY: both strings outlive the call; the handle is closed below.
            unsafe {
                if RegOpenKeyExW(
                    HKEY_LOCAL_MACHINE,
                    PCWSTR(key.as_ptr()),
                    0,
                    KEY_READ,
                    &mut handle,
                ) != ERROR_SUCCESS
                {
                    return None;
                }
                let mut buffer = [0u16; 520];
                let mut size = std::mem::size_of_val(&buffer) as u32;
                let read = RegQueryValueExW(
                    handle,
                    PCWSTR(value.as_ptr()),
                    None,
                    None,
                    Some(buffer.as_mut_ptr().cast()),
                    Some(&mut size),
                );
                let _ = RegCloseKey(handle);
                if read != ERROR_SUCCESS {
                    return None;
                }
                let end = buffer.iter().position(|&c| c == 0).unwrap_or(buffer.len());
                let text = String::from_utf16_lossy(&buffer[..end]);
                (!text.trim().is_empty()).then(|| PathBuf::from(text.trim()))
            }
        }

        /// Point the driver at a folder, and put the shipped settings in it.
        ///
        /// # Why an existing setting is left alone
        ///
        /// The key belongs to the driver, not to Tain, and this machine may
        /// already have the driver installed by its own installer with settings
        /// somebody has edited — a resolution list, an HDR option. Repointing it
        /// would orphan all of that silently, and the person it happened to
        /// would have no reason to look here.
        ///
        /// So a path already set is respected, and only the absence of one is
        /// taken as permission to choose.
        pub fn prepare(files: &[(&str, &[u8])]) -> Result<PathBuf> {
            let ours = ours().context("no ProgramData directory")?;
            match super::super::decide_settings_path(configured(), ours) {
                super::super::SettingsPath::Keep(existing) => {
                    tracing::info!(
                        "The display driver is already pointed at {} — leaving it there",
                        existing.display()
                    );
                    seed(&existing, files)?;
                    Ok(existing)
                }
                super::super::SettingsPath::Claim(dir) => {
                    seed(&dir, files)?;
                    write_path(&dir)?;
                    tracing::info!(
                        "The display driver will read its settings from {}",
                        dir.display()
                    );
                    Ok(dir)
                }
            }
        }

        /// Put the package's own settings file there, if there is not one.
        ///
        /// Never overwrites: the file is the user's once it exists, and the
        /// count in it is what the driver itself writes.
        fn seed(dir: &std::path::Path, files: &[(&str, &[u8])]) -> Result<()> {
            std::fs::create_dir_all(dir)
                .with_context(|| format!("could not create {}", dir.display()))?;
            for (name, bytes) in files {
                if !name.eq_ignore_ascii_case("vdd_settings.xml") {
                    continue;
                }
                let path = dir.join(name);
                if path.exists() {
                    tracing::debug!("{} is already there — keeping it", path.display());
                    continue;
                }
                std::fs::write(&path, bytes)
                    .with_context(|| format!("could not write {}", path.display()))?;
            }
            Ok(())
        }

        fn write_path(dir: &std::path::Path) -> Result<()> {
            let key = wide(KEY);
            let value = wide(VALUE);
            let text = wide(&dir.to_string_lossy());
            let mut handle = HKEY::default();

            // SAFETY: every string outlives its call; the handle is closed on
            // both paths.
            unsafe {
                let created = RegCreateKeyExW(
                    HKEY_LOCAL_MACHINE,
                    PCWSTR(key.as_ptr()),
                    0,
                    PCWSTR::null(),
                    REG_OPTION_NON_VOLATILE,
                    KEY_WRITE,
                    None,
                    &mut handle,
                    None,
                );
                if created != ERROR_SUCCESS {
                    anyhow::bail!("could not open {KEY} for writing ({})", created.0);
                }
                // Bytes, including the terminator, which `RegQueryValueExW`
                // relies on being there — a REG_SZ written without it is read
                // back with whatever follows it in the hive.
                let bytes = std::slice::from_raw_parts(
                    text.as_ptr().cast::<u8>(),
                    std::mem::size_of_val(&text[..]),
                );
                let written = RegSetValueExW(
                    handle,
                    PCWSTR(value.as_ptr()),
                    0,
                    REG_SZ,
                    Some(bytes),
                );
                let _ = RegCloseKey(handle);
                if written != ERROR_SUCCESS {
                    anyhow::bail!("could not set {VALUE} ({})", written.0);
                }
            }
            Ok(())
        }

        /// Undo the pointer, but only if it is still ours.
        ///
        /// The folder itself stays. It holds a settings file somebody may have
        /// edited, and an uninstall that deletes a configuration is worse than
        /// one that leaves a small directory behind.
        pub fn forget() {
            let Some(ours) = ours() else { return };
            if !super::super::may_forget_settings_path(configured(), &ours) {
                if let Some(configured) = configured() {
                    tracing::info!(
                        "{KEY}\\{VALUE} points at {} rather than Tain's folder — leaving it",
                        configured.display()
                    );
                }
                return;
            }

            let key = wide(KEY);
            let value = wide(VALUE);
            let mut handle = HKEY::default();
            // SAFETY: both strings outlive the call; the handle is closed below.
            unsafe {
                if RegOpenKeyExW(
                    HKEY_LOCAL_MACHINE,
                    PCWSTR(key.as_ptr()),
                    0,
                    KEY_WRITE,
                    &mut handle,
                ) != ERROR_SUCCESS
                {
                    return;
                }
                let _ = RegDeleteValueW(handle, PCWSTR(value.as_ptr()));
                let _ = RegCloseKey(handle);
            }
            tracing::info!("Stopped pointing the display driver at {}", ours.display());
        }
    }

    /// The driver's control pipe: how a virtual monitor comes to exist.
    ///
    /// # The protocol, read out of the driver's source
    ///
    /// There is no documentation for it. What the server does:
    ///
    /// ```text
    /// wchar_t buffer[128];
    /// ReadFile(hPipe, buffer, sizeof(buffer) - sizeof(wchar_t), &bytesRead, NULL);
    /// buffer[bytesRead / sizeof(wchar_t)] = L'\0';
    /// if (wcsncmp(buffer, L"PING", 4) == 0) { SendToPipe("PONG"); }
    /// swscanf_s(buffer + 15, L"%d", &newDisplayCount);   // after SETDISPLAYCOUNT
    /// ```
    ///
    /// So: **UTF-16**, no framing beyond the message itself, commands matched by
    /// prefix, and an argument read straight off the end of the verb. A count is
    /// `SETDISPLAYCOUNT` followed by the number — `swscanf_s` skips whitespace,
    /// so a space between them is optional and is written anyway, because a
    /// message that reads correctly is worth more than one byte.
    ///
    /// # Why no administrator rights are needed here
    ///
    /// The pipe is created with `D:(A;;GA;;;WD)` — full access to Everyone.
    /// Which is the driver's decision rather than one this can tighten: it also
    /// means any process on the machine can add and remove monitors. Worth
    /// knowing; not worth pretending otherwise.
    pub mod pipe {
        use anyhow::{bail, Context, Result};
        use windows::core::PCWSTR;
        use windows::Win32::Foundation::{CloseHandle, GENERIC_READ, GENERIC_WRITE, HANDLE};
        use windows::Win32::Storage::FileSystem::{
            CreateFileW, ReadFile, WriteFile, FILE_FLAGS_AND_ATTRIBUTES, FILE_SHARE_MODE,
            OPEN_EXISTING,
        };

        const PIPE: &str = r"\\.\pipe\MTTVirtualDisplayPipe";

        /// A driver that has just been asked to change its display count
        /// restarts, so its pipe goes away and comes back. Long enough to cover
        /// that; short enough that a driver which is simply not there does not
        /// hold the interface.
        const RETRY_FOR: std::time::Duration = std::time::Duration::from_secs(6);

        fn wide(s: &str) -> Vec<u16> {
            s.encode_utf16().chain(std::iter::once(0)).collect()
        }

        /// Open the pipe, say one thing, and read whatever comes back.
        ///
        /// The reply is best-effort: `SETDISPLAYCOUNT` restarts the driver, so
        /// the read after it usually fails with the pipe closing underneath —
        /// which is success, not failure, and is why a read error is not one.
        fn say(command: &str) -> Result<Vec<u8>> {
            let path = wide(PIPE);
            // SAFETY: the path outlives the call; the handle is closed below.
            let handle: HANDLE = unsafe {
                CreateFileW(
                    PCWSTR(path.as_ptr()),
                    GENERIC_READ.0 | GENERIC_WRITE.0,
                    FILE_SHARE_MODE(0),
                    None,
                    OPEN_EXISTING,
                    FILE_FLAGS_AND_ATTRIBUTES(0),
                    None,
                )
            }
            .with_context(|| format!("could not open {PIPE} — is the driver installed?"))?;

            let message = command.encode_utf16().collect::<Vec<u16>>();
            // SAFETY: `message` outlives the call; the byte view is its own
            // storage, and the handle is live until the close below.
            let written = unsafe {
                let bytes = std::slice::from_raw_parts(
                    message.as_ptr().cast::<u8>(),
                    std::mem::size_of_val(&message[..]),
                );
                let mut done = 0u32;
                WriteFile(handle, Some(bytes), Some(&mut done), None)
            };

            let mut reply = Vec::new();
            if written.is_ok() {
                let mut buffer = [0u8; 256];
                let mut read = 0u32;
                // SAFETY: the buffer outlives the call and its length is given.
                if unsafe { ReadFile(handle, Some(&mut buffer), Some(&mut read), None) }.is_ok() {
                    reply.extend_from_slice(&buffer[..read as usize]);
                }
            }

            // SAFETY: opened above and not closed anywhere else.
            let _ = unsafe { CloseHandle(handle) };
            written.with_context(|| format!("could not send {command} to the driver"))?;
            Ok(reply)
        }

        /// Whether the driver is running and answering.
        ///
        /// Answers `PONG`, and the reply is looked for in both encodings: the
        /// server writes it with a helper that takes a narrow string, and
        /// whether that reaches the wire as ASCII or as wide characters is not
        /// worth depending on when both are two lines to check.
        pub fn is_live() -> bool {
            let Ok(reply) = say("PING") else { return false };
            let narrow = String::from_utf8_lossy(&reply).to_ascii_uppercase();
            let wide: Vec<u16> = reply
                .chunks_exact(2)
                .map(|pair| u16::from_le_bytes([pair[0], pair[1]]))
                .collect();
            let widened = String::from_utf16_lossy(&wide).to_ascii_uppercase();
            narrow.contains("PONG") || widened.contains("PONG")
        }

        /// Ask the driver to present this many monitors.
        ///
        /// The driver writes the number into its settings and restarts itself —
        /// "Display Count Changed, Restarting Driver" — so this returns before
        /// the monitors exist. [`super::wait_for_monitors`] is the other half.
        pub fn set_display_count(count: u32) -> Result<()> {
            // A space, though `swscanf_s` does not need one: the driver logs
            // the message it received, and a log line reading
            // "SETDISPLAYCOUNT 2" is worth a byte over "SETDISPLAYCOUNT2".
            say(&format!("SETDISPLAYCOUNT {count}"))?;
            tracing::info!("Asked the display driver for {count} monitor(s)");
            Ok(())
        }

        /// Wait for the driver's pipe to come back after a restart.
        ///
        /// Polled rather than waited on: `WaitNamedPipe` waits for an *instance*
        /// of a pipe that exists, and during the restart it does not exist at
        /// all, which that call reports immediately as a failure.
        pub fn wait_until_live() -> Result<()> {
            let until = std::time::Instant::now() + RETRY_FOR;
            while std::time::Instant::now() < until {
                if is_live() {
                    return Ok(());
                }
                std::thread::sleep(std::time::Duration::from_millis(250));
            }
            bail!("the display driver did not answer within {RETRY_FOR:?}")
        }
    }

    /// Whether a Tain window is open, which is what a display's lifetime hangs
    /// on.
    ///
    /// # The problem
    ///
    /// A virtual display outlives the process that made it. Nothing about a
    /// monitor on the desktop says who put it there, so closing Tain — or
    /// killing it, or watching it crash — leaves a screen behind that shoves
    /// windows onto itself and that nobody can see anything on. Asked for
    /// directly: *"virtual display should disappear upon closing Tain.exe
    /// (gracefully or not)"*.
    ///
    /// # A handle, rather than a note on disk
    ///
    /// Tain holds a named mutex for as long as it is running, and that is the
    /// entire mechanism. It is the kernel's bookkeeping and not this code's: a
    /// handle is closed when the process holding it ends, whether it ended by
    /// being asked to, by crashing, or by being killed from Task Manager. There
    /// is no sequence of events in which the record outlives the thing it
    /// records, which is exactly the property a file full of process ids does
    /// not have.
    ///
    /// # `Local\`, not `Global\`
    ///
    /// The agent that reaps orphaned displays runs in the console session,
    /// which is the session whose desktop the display is on — so a
    /// session-local name is the right scope rather than a compromise. It also
    /// needs no privilege to create, where a global name needs
    /// `SeCreateGlobalPrivilege`. That matters more than it looks: if
    /// announcing could fail, there would be a case where a running Tain went
    /// unnoticed and had its display taken away underneath it, and the whole
    /// point of this module is that that case does not exist.
    pub mod presence {
        use windows::core::PCWSTR;
        use windows::Win32::Foundation::{CloseHandle, HANDLE};
        use windows::Win32::System::Threading::{
            CreateMutexW, OpenMutexW, SYNCHRONIZATION_SYNCHRONIZE,
        };

        /// Session-local, so the console session's agent sees the console
        /// session's application and nothing else.
        const NAME: &str = r"Local\Tain.Application";

        /// Held for as long as this process counts as a running Tain.
        ///
        /// Never locked. A mutex is used for its *existence*, which is what
        /// [`is_running`] asks about — taking ownership would say something
        /// about one process among several, and several are allowed.
        pub struct Presence(HANDLE);

        impl Drop for Presence {
            fn drop(&mut self) {
                // SAFETY: opened in `announce` and closed once, here.
                unsafe {
                    let _ = CloseHandle(self.0);
                }
            }
        }

        // SAFETY: a kernel handle is a process-wide value with no thread
        // affinity, and the only thing done with this one is closing it.
        unsafe impl Send for Presence {}

        fn wide(s: &str) -> Vec<u16> {
            s.encode_utf16().chain(std::iter::once(0)).collect()
        }

        /// Say that a Tain application is running here, until the value drops.
        ///
        /// An existing mutex is opened rather than fought over: two copies of
        /// Tain are allowed, and the name outlives both only if both are gone.
        pub fn announce() -> Option<Presence> {
            let name = wide(NAME);
            // SAFETY: the name outlives the call. `false` asks not to take
            // ownership, which this never wants — see the note on `Presence`.
            let handle = unsafe { CreateMutexW(None, false, PCWSTR(name.as_ptr())) };
            match handle {
                Ok(handle) => Some(Presence(handle)),
                Err(e) => {
                    // Nothing stops working. What is lost is the agent's
                    // ability to tell that this process is alive, so it says so
                    // plainly rather than leaving a display to vanish for no
                    // visible reason.
                    tracing::warn!(
                        "Could not announce this Tain to the rest of the machine ({e}). \
                         A virtual display may be put away while it is still in use."
                    );
                    None
                }
            }
        }

        /// Whether any Tain application is running in this session.
        pub fn is_running() -> bool {
            let name = wide(NAME);
            // SAFETY: the name outlives the call; the handle is closed below.
            let opened =
                unsafe { OpenMutexW(SYNCHRONIZATION_SYNCHRONIZE, false, PCWSTR(name.as_ptr())) };
            match opened {
                Ok(handle) => {
                    // SAFETY: just opened, closed once, here.
                    unsafe {
                        let _ = CloseHandle(handle);
                    }
                    true
                }
                // Every failure reads as absent. The one that matters is
                // "no such object", and the others — a name that cannot be
                // opened for permissions, say — are not states this creates.
                Err(_) => false,
            }
        }
    }

    /// Take away displays whose application has gone.
    ///
    /// # Why this is not simply done when Tain closes
    ///
    /// It is, and that covers the ordinary case. It does not cover the case
    /// that was asked about: a process that is killed, or crashes, runs no exit
    /// path at all, and the display it attached stays on the desktop with
    /// nothing left to take it off.
    ///
    /// So something that outlives the application has to do it. That is the
    /// agent — the service cannot, because a service is in session zero and
    /// display configuration belongs to the session whose desktop it is, while
    /// the agent runs in the console session and can.
    ///
    /// # What it refuses to touch
    ///
    /// Only this driver's displays ([`ours`]), and only when Tain installed the
    /// driver ([`installed_by_tain`]). Somebody who installed the same driver
    /// themselves and keeps a virtual screen up permanently would otherwise
    /// lose it every time Tain was not running, on the strength of Tain having
    /// recognised the name of a driver it did not put there.
    ///
    /// Returns how many it removed, so a caller can log the interesting case
    /// and stay quiet the rest of the time — which is nearly always, since this
    /// runs on a timer.
    pub fn reap_orphans() -> usize {
        if presence::is_running() {
            return 0;
        }
        // Cheapest question first: this runs on a timer and the answer is
        // almost always that there is nothing on the desktop to think about.
        if !ours(package().as_ref()).iter().any(|screen| screen.attached) {
            return 0;
        }
        release()
    }

    /// Put away every virtual display Tain is responsible for.
    ///
    /// What [`reap_orphans`] does once it has established that nobody is using
    /// them, and what the application does as it closes — where the question
    /// does not arise, because the application closing is the thing that would
    /// have been waited for.
    ///
    /// Gated on [`installed_by_tain`] for the reason given there: a driver
    /// somebody else installed is not Tain's to take displays away from.
    pub fn release() -> usize {
        if !installed_by_tain() {
            return 0;
        }
        stand_down()
    }

    /// Wait until the driver has presented at least this many monitors.
    ///
    /// Adapters exist from the moment the driver is installed and mean nothing;
    /// what is being waited for is a monitor *behind* one — see
    /// [`tain_core::virtual_display`], whose `ready` is that question.
    fn wait_for_monitors(at_least: usize, within: std::time::Duration) -> Result<()> {
        let package = package();
        let until = std::time::Instant::now() + within;
        loop {
            let ready =
                ours(package.as_ref()).iter().filter(|screen| screen.ready).count();
            if ready >= at_least {
                return Ok(());
            }
            if std::time::Instant::now() >= until {
                bail!(
                    "the driver reported {ready} monitor(s) after {within:?}, wanted {at_least}"
                );
            }
            std::thread::sleep(std::time::Duration::from_millis(250));
        }
    }

    /// The fewest monitors this driver will present.
    ///
    /// Not a choice — it reads a count of zero as invalid and substitutes one.
    /// Which is why nothing here tries to reach none by asking: taking a
    /// display off the desktop is what removal means, and [`remove_display`]
    /// says why at length.
    const MIN_PRESENTED: usize = 1;

    /// How long a driver restart is given to produce its monitors.
    ///
    /// Generous: the driver tears itself down and comes back, Windows
    /// re-enumerates the adapters, and a machine doing something else at the
    /// time is slower still. Waiting a few seconds too long costs a progress
    /// spinner; giving up too early reports a failure that did not happen.
    const MONITOR_WAIT: std::time::Duration = std::time::Duration::from_secs(20);

    /// How long Windows is given to put a new monitor on the desktop.
    ///
    /// Short, because unlike the wait above this one has no answer it is hoping
    /// for: Windows may attach the monitor or leave it alone, and both are
    /// ordinary. Waiting is only worth the time it takes to stop racing it.
    const ATTACH_WAIT: std::time::Duration = std::time::Duration::from_secs(3);

    /// The sizes a virtual display can actually be set to, largest first.
    ///
    /// Taken from a presented monitor rather than from the settings file: the
    /// file is what the driver was *asked* for, and a list read back from the
    /// device is what it will accept. Offering a size the driver refuses is a
    /// menu entry that fails on click.
    ///
    /// Empty until a monitor exists, which is why the picker falls back to the
    /// primary display's size — there is nothing to enumerate before the first
    /// one is created.
    pub fn offered_sizes() -> Vec<(u16, u16)> {
        let Some(screen) =
            ours(package().as_ref()).into_iter().find(|screen| screen.ready)
        else {
            return Vec::new();
        };
        let mut sizes: Vec<(u16, u16)> = tain_core::virtual_display::modes(&screen.name)
            .into_iter()
            .map(|mode| (mode.width, mode.height))
            .collect::<std::collections::BTreeSet<_>>()
            .into_iter()
            .collect();
        // Largest first: somebody opening this list is far more often reaching
        // for a big one than a small one.
        sizes.sort_by_key(|(w, h)| std::cmp::Reverse(u32::from(*w) * u32::from(*h)));
        sizes
    }

    
    /// How many virtual displays are on the desktop right now.
    ///
    /// Attached ones, not presented ones. The driver keeps an idle monitor
    /// after the last display is removed — it will not accept a count of zero
    /// — and counting that would leave the interface insisting there is a
    /// screen the user has just taken away and cannot see.
    pub fn monitor_count() -> usize {
        ours(package().as_ref())
            .iter()
            .filter(|screen| screen.ready && screen.attached)
            .count()
    }

    /// Add a virtual display and put it on the desktop.
    ///
    /// Two steps that belong together and are usually confused for one: the
    /// driver has to *present* a monitor, and Windows has to be told to put it
    /// on the desktop. A monitor nobody attached exists, offers modes, and shows
    /// nothing.
    ///
    /// Needs no administrator rights. Installing the driver did; this does not.
    pub fn add_display(size: (u16, u16)) -> Result<String> {
        // # A monitor the driver is already presenting is the one to use
        //
        // Removing a display takes it off the desktop and, when it is the last
        // one, leaves the driver still presenting it — because a count of zero
        // is not something this driver will accept. See [`remove_display`].
        //
        // So "add" usually has one sitting there already, and putting it back
        // on the desktop is instant where raising the count is a driver
        // restart and several seconds of waiting.
        let package = package();
        if let Some(spare) =
            ours(package.as_ref()).into_iter().find(|screen| screen.ready && !screen.attached)
        {
            place(&spare.name, size)?;
            return Ok(spare.name);
        }

        let before: std::collections::BTreeSet<String> = ours(package.as_ref())
            .into_iter()
            .filter(|screen| screen.ready)
            .map(|screen| screen.name)
            .collect();

        pipe::set_display_count(before.len() as u32 + 1)?;
        // The driver restarts, so its pipe goes before it comes back. Waiting
        // for that first means the monitor wait is not also waiting for a
        // process to start.
        pipe::wait_until_live()?;
        wait_for_monitors(before.len() + 1, MONITOR_WAIT)?;

        // The new one, by elimination. Named by device rather than by index
        // because the numbers move when a monitor is plugged in.
        let fresh = ours(package.as_ref())
            .into_iter()
            .find(|screen| screen.ready && !before.contains(&screen.name))
            .context("the driver presented a monitor that could not be identified")?;

        place(&fresh.name, size)?;
        Ok(fresh.name)
    }

    /// Put a presented monitor on the desktop, at a size, in its own space.
    ///
    /// # Placed whether or not Windows already attached it
    ///
    /// This used to be skipped for a display that was already attached, on the
    /// reasoning that there was nothing left to do. There was: Windows chooses
    /// a topology when a monitor arrives and very often chooses **clone**,
    /// which is attached, reports a size, and is a second copy of the primary
    /// at the same coordinates. Nothing to capture, nowhere for a pointer to
    /// go, and the only way out was a trip to Settings — reported for the
    /// virtual display and for a dummy HDMI plug alike.
    ///
    /// The topology is set first, because a position cannot undo a clone:
    /// `ChangeDisplaySettingsExW` moves a display *within* a topology and is
    /// entitled to ignore the request otherwise.
    fn place(name: &str, size: (u16, u16)) -> Result<()> {
        if let Err(e) = tain_core::virtual_display::extend_desktop() {
            // Not fatal. A machine with one display has nothing to extend, and
            // the placement below is the part that has to work.
            tracing::debug!("Could not set the desktop to extend: {e:#}");
        }
        tain_core::virtual_display::attach(name, size, 60)?;
        tracing::info!("Virtual display {name} is on the desktop at {}x{}", size.0, size.1);
        Ok(())
    }

    /// Take the most recently added virtual display away again.
    ///
    /// Detached first, so the desktop stops using it before it stops existing —
    /// a monitor removed from under a window leaves the window somewhere
    /// nobody chose.
    pub fn remove_display() -> Result<()> {
        let screens = ours(package().as_ref());
        let Some(last) = screens.iter().rfind(|s| s.ready && s.attached) else {
            return Ok(());
        };

        // # Taking it off the desktop *is* the removal
        //
        // Asking the driver for one monitor fewer looks like the tidier answer
        // and is not, in two separate ways.
        //
        // Zero does not work at all. The driver writes the number, restarts,
        // reads it back, and decides it is wrong:
        //
        //   if (monitorcount == 0) {
        //       monitorcount = 1;
        //       vddlog("i", "Loading singular monitor (Monitor Count is not valid)");
        //   }
        //
        // So it presents one anyway, and a monitor arriving is a monitor
        // Windows attaches — the removal recreating precisely the thing it had
        // just taken away.
        //
        // And lowering a count above one has the same shape for a subtler
        // reason: *any* change to the count restarts the driver, so every
        // monitor it presents goes away and comes back, and one that comes back
        // is one Windows may put on the desktop. Undoing the detach that just
        // succeeded, in the name of tidying up after it.
        //
        // Detaching is what was actually asked for. The screen is off the
        // desktop, out of `displays()`, not offered to a guest and not
        // capturable. What remains is a monitor the driver presents and nothing
        // shows — which costs a little memory, and which `add_display` reuses,
        // making the next display instant rather than a restart and a wait. The
        // count therefore only ever rises to the most displays that were wanted
        // at once, and `install` puts it back to one.
        tain_core::virtual_display::detach(&last.name)
            .with_context(|| format!("could not take {} off the desktop", last.name))?;
        Ok(())
    }

    /// Take every one of this driver's displays off the desktop.
    ///
    /// Returns how many were removed, and reports the ones that would not go
    /// rather than failing on the first: this runs where nobody is watching —
    /// as an application closes, after an install, from the agent — and a
    /// display left behind because an earlier one refused would be the worst of
    /// both.
    ///
    /// Does not lower the driver's count. What is left is a monitor the driver
    /// presents and nothing displays, which costs a little memory and makes the
    /// next [`add_display`] instant; asking for fewer would mean a driver
    /// restart, and asking for none does not work at all — see
    /// [`remove_display`].
    pub fn stand_down() -> usize {
        let package = package();
        let mut removed = 0;
        for screen in ours(package.as_ref()).into_iter().filter(|s| s.attached) {
            match tain_core::virtual_display::detach(&screen.name) {
                Ok(()) => removed += 1,
                Err(e) => tracing::warn!("Could not put {} away: {e:#}", screen.name),
            }
        }
        removed
    }

    /// Put away the display that installing the driver brings with it.
    ///
    /// # Why installing produces a display nobody asked for
    ///
    /// The driver presents a monitor the moment it starts, because it will not
    /// accept a count of none — a zero in its settings is read back as invalid
    /// and replaced with one. Windows attaches whatever monitor arrives. So the
    /// end of a successful install is a desktop with an extra screen on it,
    /// which is not what "install the driver" means: installing is being able
    /// to make a display, and making one is a separate button.
    ///
    /// Reported and reinstalled straight after the first time, as *"if I
    /// uninstall, then install again, it automatically comes back without me
    /// pressing add monitor"*.
    ///
    /// # Why the count is lowered first
    ///
    /// Uninstalling leaves the settings file behind on purpose — it may hold
    /// things somebody edited — and the count is in it. So a machine that had
    /// three displays gets three back on the next install. One is the fewest
    /// the driver accepts, and lowering it first means the wait below is for
    /// one monitor rather than for three that are all about to be put away.
    ///
    /// Nothing here can fail the install. The driver is installed by the time
    /// this runs; a tidy-up that did not work is worth a log line and not an
    /// error message about an install that succeeded.
    fn settle_after_install() {
        if let Err(e) = pipe::wait_until_live() {
            tracing::info!("The driver is installed but not answering yet: {e:#}");
            return;
        }

        let presented =
            ours(package().as_ref()).iter().filter(|screen| screen.ready).count();
        if presented > MIN_PRESENTED {
            tracing::info!(
                "An earlier install left {presented} monitors configured — asking for {MIN_PRESENTED}"
            );
            if let Err(e) = pipe::set_display_count(MIN_PRESENTED as u32)
                .and_then(|()| pipe::wait_until_live())
            {
                tracing::warn!("Could not lower the monitor count: {e:#}");
            }
        }

        if let Err(e) = wait_for_monitors(MIN_PRESENTED, MONITOR_WAIT) {
            tracing::info!("Nothing to put away after installing: {e:#}");
            return;
        }
        // Presenting a monitor and Windows putting it on the desktop are two
        // events, and the second trails the first by a moment. Detaching before
        // it happens removes nothing and leaves the display to arrive
        // afterwards, which is the bug this exists to prevent.
        wait_for_attachment(ATTACH_WAIT);

        match stand_down() {
            0 => tracing::info!("The driver is installed and presenting nothing on the desktop"),
            n => tracing::info!(
                "Put away {n} display(s) the install brought with it — \
                 use Add a display to create one"
            ),
        }
    }

    /// Wait for Windows to put one of this driver's monitors on the desktop.
    ///
    /// Returns whether it did. Not an error either way: Windows is entitled to
    /// leave a monitor unattached, and a caller that wanted one gone has
    /// nothing to do in that case.
    fn wait_for_attachment(within: std::time::Duration) -> bool {
        let package = package();
        let until = std::time::Instant::now() + within;
        loop {
            if ours(package.as_ref()).iter().any(|screen| screen.attached) {
                return true;
            }
            if std::time::Instant::now() >= until {
                return false;
            }
            std::thread::sleep(std::time::Duration::from_millis(200));
        }
    }

    /// Create the device node and bind the driver to it.
    ///
    /// Must already be running as administrator; this is what the elevated
    /// relaunch above ends up calling.
    pub fn install() -> Result<()> {
        let package = package().context("this build ships no driver package")?;
        // An embedded package has to exist on disk before Windows can be
        // pointed at it: the install reads the `.inf`, and the `.cat` beside it.
        let inf = if package.embedded {
            unpack()?.join(&package.inf)
        } else {
            package.inf.clone()
        };
        // Absolute, because `newdev` resolves a relative path against the
        // system directory rather than against this process.
        let inf = inf
            .canonicalize()
            .with_context(|| format!("could not resolve {}", inf.display()))?;
        device::create(&package.class, &package.hardware_id)?;
        device::bind(&inf, &package.hardware_id)?;
        // After the driver is bound, because a settings folder pointing at
        // nothing is litter, and before anything asks for a monitor: the count
        // lives in that file and the driver reads it at every start.
        let settings = settings::prepare(embedded::FILES)?;
        tracing::info!("Driver settings live in {}", settings.display());
        tracing::info!(
            "Installed {} ({}) from {}",
            package.device_name.as_deref().unwrap_or("the virtual display driver"),
            package.hardware_id,
            inf.display()
        );
        // The driver starts presenting a monitor as soon as it is bound, and
        // Windows attaches whatever arrives — so an install ends with a screen
        // on the desktop unless something puts it away.
        settle_after_install();
        Ok(())
    }

    /// Remove the device node. Must already be running as administrator.
    ///
    /// Reads the id from the package for the same reason installing does: the
    /// device is the package's, not ours, and a build shipping a different one
    /// must remove the one it installed.
    pub fn uninstall() -> Result<()> {
        let package = package().context("this build ships no driver package")?;
        let removed = device::remove(&package.class, &package.hardware_id)?;
        settings::forget();
        if removed == 0 {
            tracing::info!("No virtual display device to remove");
        } else {
            tracing::info!("Removed {removed} virtual display device(s)");
        }
        Ok(())
    }

    /// The SetupAPI half: making a device out of nothing and giving it a driver.
    ///
    /// This is what `devcon install` does, and there is no higher-level way to
    /// do it — a root-enumerated device has no hardware to be discovered, so
    /// something has to assert that it exists.
    mod device {
        use anyhow::{bail, Context, Result};
        use std::path::Path;
        use windows::core::PCWSTR;
        use windows::Win32::Devices::DeviceAndDriverInstallation::{
            SetupDiCallClassInstaller, SetupDiCreateDeviceInfoList, SetupDiCreateDeviceInfoW,
            SetupDiDestroyDeviceInfoList, SetupDiEnumDeviceInfo, SetupDiGetClassDevsW,
            SetupDiGetDeviceRegistryPropertyW, SetupDiSetDeviceRegistryPropertyW,
            UpdateDriverForPlugAndPlayDevicesW, DICD_GENERATE_ID, DIF_REGISTERDEVICE,
            DIF_REMOVE, DIGCF_PRESENT, HDEVINFO, INSTALLFLAG_FORCE, SPDRP_HARDWAREID,
            SP_DEVINFO_DATA,
        };
        use windows::Win32::Foundation::{BOOL, HWND};

        /// No parent window: this runs from a relaunched, elevated process with
        /// no interface of its own, and every one of these calls takes one only
        /// to parent a dialog it will not show.
        const NO_PARENT: HWND = HWND(std::ptr::null_mut());

        /// The class the `.inf` says its device belongs to.
        ///
        /// Read from the package rather than assumed to be
        /// `GUID_DEVCLASS_DISPLAY`: a device has to be created in the class its
        /// driver expects to be installed into, and a package is free to name
        /// one — this is where a typo in somebody's `.inf` becomes a device no
        /// driver will ever bind to, and taking the value from the file means
        /// the two cannot disagree.
        /// Parsed here rather than with `GUID::try_from`, which panics on
        /// anything malformed. This value comes out of a file on disk, and a
        /// file being wrong is a thing to report, not to abort on.
        fn class_guid(text: &str) -> Result<windows::core::GUID> {
            let digits: String = text
                .trim()
                .trim_start_matches('{')
                .trim_end_matches('}')
                .chars()
                .filter(|c| *c != '-')
                .collect();
            if digits.len() != 32 || !digits.chars().all(|c| c.is_ascii_hexdigit()) {
                bail!("{} is not a class GUID", text.trim());
            }
            let bits = u128::from_str_radix(&digits, 16)
                .with_context(|| format!("{} is not a class GUID", text.trim()))?;
            Ok(windows::core::GUID::from_u128(bits))
        }

        fn wide(s: &str) -> Vec<u16> {
            s.encode_utf16().chain(std::iter::once(0)).collect()
        }

        /// A hardware id list is REG_MULTI_SZ: each string NUL-terminated, and
        /// the whole thing terminated again. One id here, so two NULs.
        fn multi_sz(s: &str) -> Vec<u16> {
            s.encode_utf16().chain([0, 0]).collect()
        }

        /// Assert that a device with this hardware id exists.
        ///
        /// Idempotent: a second call makes a second device node, so this checks
        /// first. Two nodes claiming one driver is not fatal, but it doubles
        /// the adapters and leaves one of them impossible to remove by name.
        pub fn create(class: &str, hardware_id: &str) -> Result<()> {
            let class = class_guid(class)?;
            if count(&class, hardware_id)? > 0 {
                tracing::info!("The virtual display device is already registered");
                return Ok(());
            }

            // SAFETY: every pointer below is either null or points at a local
            // that outlives the call; the info list is destroyed on both paths.
            unsafe {
                let list = SetupDiCreateDeviceInfoList(Some(&class), NO_PARENT)
                    .context("could not start a device installation")?;

                let result = (|| -> Result<()> {
                    // The device *name* is a prefix Windows appends an index
                    // to when generating the instance id, not the class — a
                    // separate thing from `class` above that happens to read
                    // the same, which is how the two got confused once already.
                    let name_prefix = wide("Display");
                    let mut info = SP_DEVINFO_DATA {
                        cbSize: std::mem::size_of::<SP_DEVINFO_DATA>() as u32,
                        ..Default::default()
                    };
                    SetupDiCreateDeviceInfoW(
                        list,
                        PCWSTR(name_prefix.as_ptr()),
                        &class,
                        PCWSTR::null(),
                        NO_PARENT,
                        DICD_GENERATE_ID,
                        Some(&mut info),
                    )
                    .context("could not create the device entry")?;

                    let ids = multi_sz(hardware_id);
                    let bytes = std::slice::from_raw_parts(
                        ids.as_ptr() as *const u8,
                        std::mem::size_of_val(&ids[..]),
                    );
                    SetupDiSetDeviceRegistryPropertyW(
                        list,
                        &mut info,
                        SPDRP_HARDWAREID,
                        Some(bytes),
                    )
                    .context("could not name the device")?;

                    // The step that makes it real. Everything above it lives
                    // only in this process's copy of the device info list.
                    SetupDiCallClassInstaller(DIF_REGISTERDEVICE, list, Some(&info as *const _))
                        .context("Windows refused to register the device")?;
                    Ok(())
                })();

                let _ = SetupDiDestroyDeviceInfoList(list);
                result
            }
        }

        /// Give the device a driver, from an `.inf` on disk.
        ///
        /// `INSTALLFLAG_FORCE` because the device was just created with no
        /// driver at all, so there is nothing to compare against and the
        /// ordinary "is this better than what is there" rule has no answer.
        pub fn bind(inf: &Path, hardware_id: &str) -> Result<()> {
            let inf_path = wide(&inf.to_string_lossy());
            let id = wide(hardware_id);
            let mut reboot = BOOL(0);

            // SAFETY: both strings outlive the call and `reboot` is a valid
            // out-parameter.
            unsafe {
                UpdateDriverForPlugAndPlayDevicesW(
                    NO_PARENT,
                    PCWSTR(id.as_ptr()),
                    PCWSTR(inf_path.as_ptr()),
                    INSTALLFLAG_FORCE,
                    Some(&mut reboot),
                )
            }
            .with_context(|| format!("Windows would not install {}", inf.display()))?;

            if reboot.as_bool() {
                tracing::warn!("Windows says the driver needs a restart to finish");
            }
            Ok(())
        }

        /// Remove every device with this hardware id. Returns how many.
        pub fn remove(class: &str, hardware_id: &str) -> Result<u32> {
            let class = class_guid(class)?;
            with_devices(&class, hardware_id, |list, info| {
                // SAFETY: both come from the enumeration above and are live.
                unsafe { SetupDiCallClassInstaller(DIF_REMOVE, list, Some(info as *const _)) }
                    .context("Windows refused to remove the device")
            })
        }

        fn count(class: &windows::core::GUID, hardware_id: &str) -> Result<u32> {
            with_devices(class, hardware_id, |_, _| Ok(()))
        }

        /// Walk the display class for devices with this hardware id.
        fn with_devices(
            class: &windows::core::GUID,
            hardware_id: &str,
            mut act: impl FnMut(HDEVINFO, &SP_DEVINFO_DATA) -> Result<()>,
        ) -> Result<u32> {
            let wanted = hardware_id.to_ascii_lowercase();

            // SAFETY: the handle is destroyed on both paths; every out-param
            // below points at a local that outlives its call.
            unsafe {
                let list = SetupDiGetClassDevsW(
                    Some(class),
                    PCWSTR::null(),
                    NO_PARENT,
                    DIGCF_PRESENT,
                )
                .context("could not enumerate display devices")?;

                let result = (|| -> Result<u32> {
                    let mut matched = 0;
                    for index in 0.. {
                        let mut info = SP_DEVINFO_DATA {
                            cbSize: std::mem::size_of::<SP_DEVINFO_DATA>() as u32,
                            ..Default::default()
                        };
                        if SetupDiEnumDeviceInfo(list, index, &mut info).is_err() {
                            break;
                        }

                        let mut buffer = [0u8; 512];
                        let mut needed = 0u32;
                        if SetupDiGetDeviceRegistryPropertyW(
                            list,
                            &info,
                            SPDRP_HARDWAREID,
                            None,
                            Some(&mut buffer),
                            Some(&mut needed),
                        )
                        .is_err()
                        {
                            continue;
                        }

                        // REG_MULTI_SZ, and any of the ids may be the one.
                        let words = std::slice::from_raw_parts(
                            buffer.as_ptr() as *const u16,
                            buffer.len() / 2,
                        );
                        let found = words
                            .split(|&c| c == 0)
                            .filter(|part| !part.is_empty())
                            .any(|part| String::from_utf16_lossy(part).to_ascii_lowercase() == wanted);
                        if !found {
                            continue;
                        }

                        matched += 1;
                        act(list, &info)?;
                    }
                    Ok(matched)
                })();

                let _ = SetupDiDestroyDeviceInfoList(list);
                result
            }
        }

        /// Sanity: the multi-sz encoding is what the registry expects.
        #[cfg(test)]
        mod tests {
            use super::*;

            #[test]
            fn a_hardware_id_list_is_terminated_twice() {
                let encoded = multi_sz("Root\\TainVirtualDisplay");
                assert_eq!(&encoded[encoded.len() - 2..], &[0, 0]);
                assert_eq!(
                    String::from_utf16_lossy(&encoded[..encoded.len() - 2]),
                    "Root\\TainVirtualDisplay"
                );
            }

            /// The class comes out of the file, braces and all.
            #[test]
            fn a_class_guid_is_read_from_the_inf_rather_than_assumed() {
                let parsed = class_guid("{4D36E968-E325-11CE-BFC1-08002BE10318}")
                    .expect("a well-formed class");
                assert_eq!(
                    format!("{parsed:?}").to_lowercase(),
                    "4d36e968-e325-11ce-bfc1-08002be10318"
                );
                // Every way a file can be wrong, reported rather than fatal.
                for bad in ["Display", "", "{}", "{4D36E968}", "{ZZZZZZZZ-E325-11CE-BFC1-08002BE10318}"] {
                    assert!(class_guid(bad).is_err(), "{bad:?} was accepted as a GUID");
                }
                // And without the braces, which an .inf is free to omit.
                assert!(class_guid("4D36E968-E325-11CE-BFC1-08002BE10318").is_ok());
            }
        }
    }
}

