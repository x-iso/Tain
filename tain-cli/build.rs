//! Mirrors `tain-core`'s ffmpeg detection, and puts the DLLs where the exe is.
//!
//! A build script only sets `cfg` for its own crate, so the `db_ffmpeg` flag
//! `tain-core` raises is invisible here. This repeats the same check — cheap, and
//! cheaper than a Cargo feature that could be set inconsistently between the two.
//!
//! It also copies the runtime DLLs next to the binary. Without that `cargo run`
//! produces a process that exits before `main` with no message, because Windows
//! resolves imports before any of our code runs.

use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-env-changed=FFMPEG_DIR");
    println!("cargo:rustc-check-cfg=cfg(db_ffmpeg)");

    embed_display_driver();

    if !cfg!(target_os = "windows") {
        return;
    }

    let Some(dir) = ffmpeg_dir() else { return };
    if !dir.join("include/libavcodec/avcodec.h").exists() {
        return;
    }
    println!("cargo:rustc-cfg=db_ffmpeg");

    // # Make the optional dependency actually optional
    //
    // ffmpeg is meant to be optional: without it the guest falls back to the
    // Media Foundation decoder. Linked as an ordinary import that is a lie —
    // Windows resolves the whole import graph before `main` runs, so an exe
    // that cannot find a DLL dies with a system error box and no log line.
    //
    // Delay loading defers the resolve to the first call, which lets
    // `FfmpegDecoder::new` probe for the library and return an error the caller
    // already knows how to handle.
    //
    // ## Why the shipped import libraries are not enough
    //
    // The prebuilt ffmpeg is a MinGW build, and its `.lib` files are GNU-format
    // import libraries — the symbols are `__libavcodec_avcodec_lib_iname` and
    // friends rather than MSVC's `__IMPORT_DESCRIPTOR_*`. link.exe resolves
    // against those happily, but `/DELAYLOAD` only builds thunks for MSVC-style
    // import descriptors, so it silently does nothing: no error, no LNK4199,
    // and `dumpbin /HEADERS` reports an empty Delay Import Directory.
    //
    // Regenerating the import libraries from the DLLs' own export tables
    // produces MSVC-format ones, and then delay loading works as documented.
    // The MSVC-format import libraries are generated by tain-core's build
    // script, which is the crate that actually emits the link-lib directives.
    // These flags are what turn them into delay-loaded imports; see that script
    // for why the shipped GNU libraries cannot be used for this.
    for dll in ["avcodec-61.dll", "avutil-59.dll"] {
        println!("cargo:rustc-link-arg-bins=/DELAYLOAD:{dll}");
    }
    println!("cargo:rustc-link-arg-bins=delayimp.lib");

    let Some(target) = target_dir() else {
        println!("cargo:warning=could not locate the target directory — ffmpeg DLLs not copied");
        return;
    };
    // # Only what is actually needed
    //
    // avcodec depends on avutil and swresample; nothing depends on avdevice,
    // avfilter, avformat or swscale, which were being copied anyway at 53 MB.
    //
    // These are for `cargo run` convenience. A distributed build needs no DLLs
    // at all — they are embedded in the binary; see tain-core's `ffmpeg_runtime`.
    for dll in ["avutil-59.dll", "swresample-5.dll", "avcodec-61.dll"] {
        let from = dir.join("bin").join(dll);
        if !from.exists() {
            continue;
        }
        for out in [&target, &target.join("deps")] {
            if !out.is_dir() {
                continue;
            }
            let to = out.join(dll);
            // Skip an identical copy: this runs on every build.
            let same = std::fs::metadata(&to)
                .ok()
                .zip(std::fs::metadata(&from).ok())
                .is_some_and(|(a, b)| a.len() == b.len());
            if !same {
                let _ = std::fs::copy(&from, &to);
            }
        }
    }
}

/// Build the virtual display driver package into the executable.
///
/// # Why it is embedded rather than shipped beside the exe
///
/// It was going to be a folder next to the binary, and that is a maintainer's
/// path wearing a user's clothes: anybody able to extract a driver package into
/// the right directory could have run the driver's own installer and skipped
/// Tain entirely. A feature that only works for people who did not need it is
/// not a feature.
///
/// So it goes in the binary, which is what this project already does with the
/// ffmpeg runtime — see `tain_core::ffmpeg_runtime`, which carries 66 MB of
/// DLLs the same way and writes them out on first use. This is 132 KB. Tain
/// stays one file, the button works on a machine that has never been online,
/// and there is nothing to put anywhere.
///
/// Uncompressed, unlike the DLLs. Those are zstd'd because 66 MB in an
/// executable is unpleasant to copy around; at this size the compression would
/// cost more in machinery than it saves in bytes.
///
/// Absent is not an error. A source tree without the folder builds a Tain
/// whose driver section says it ships no driver — the same
/// arrangement ffmpeg has, and for the same reason: a missing optional
/// dependency should cost the feature, not the build.
fn embed_display_driver() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets this");
    let vendored = Path::new(&manifest).parent().map(|p| p.join(DRIVER_DIR));
    println!("cargo:rerun-if-changed=../{DRIVER_DIR}");

    let mut entries = Vec::new();
    if let Some(dir) = vendored.as_ref().filter(|d| d.is_dir()) {
        // Flat, and one level only. A driver package is a handful of files in
        // one directory; walking deeper would be inventing a layout rather than
        // reading one.
        let mut files: Vec<PathBuf> = std::fs::read_dir(dir)
            .into_iter()
            .flatten()
            .filter_map(|entry| entry.ok())
            .map(|entry| entry.path())
            .filter(|path| path.is_file())
            .collect();
        // Sorted so the generated file is the same on every machine.
        files.sort();
        for file in files {
            let Some(name) = file.file_name().and_then(|n| n.to_str()) else { continue };
            // # Skipped by name, not selected by name
            //
            // The folder holds the signed package plus the notes that have to
            // travel with it — a licence, a provenance record. Those are not
            // part of what Windows installs and should not be written into the
            // staging directory beside the `.inf`.
            //
            // A list of what to *keep* would have been tidier and is the wrong
            // risk: a package with a file type not on it would install missing
            // a piece, which fails at the point of use and reports success.
            // Carrying an extra text file into the staging directory is
            // untidy, and Windows ignores it.
            let documentation = name.eq_ignore_ascii_case("LICENSE")
                || name.to_ascii_lowercase().ends_with(".md")
                || name.to_ascii_lowercase().ends_with(".txt");
            if documentation {
                continue;
            }
            entries.push(format!(
                "    ({name:?}, include_bytes!({:?})),\n",
                file.to_string_lossy()
            ));
        }
    }

    // A plain comment, not `//!`: this is `include!`d into the middle of a
    // module, where an inner doc comment is not allowed to appear.
    let generated = format!(
        "// Generated by build.rs from `{DRIVER_DIR}`. Empty when nothing is vendored.\n\
         pub static FILES: &[(&str, &[u8])] = &[\n{}];\n",
        entries.concat()
    );
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets this"))
        .join("display_driver_package.rs");
    // Written even when empty, so the `include!` in `display_driver` does not
    // have to be conditional on something only this script knows.
    std::fs::write(&out, generated).expect("could not write the driver package list");
}

/// Where the vendored driver package lives, relative to the workspace root.
///
/// Beside `third_party/ffmpeg` and committed the same way, because it is the
/// same kind of thing: a third-party binary this project embeds, with a
/// `PROVENANCE.md` saying where it came from.
///
/// Named as the release archive unpacks it, so re-fetching a newer one is a
/// matter of replacing the folder rather than also remembering to rename it.
const DRIVER_DIR: &str = "third_party/VirtualDisplayDriver";

fn ffmpeg_dir() -> Option<PathBuf> {
    if let Ok(dir) = std::env::var("FFMPEG_DIR") {
        let path = PathBuf::from(dir);
        return path.exists().then_some(path);
    }
    let manifest = std::env::var("CARGO_MANIFEST_DIR").ok()?;
    let candidate = Path::new(&manifest).parent()?.join("third_party/ffmpeg");
    candidate.exists().then_some(candidate)
}

/// The directory the binary is written to, walked up from `OUT_DIR`.
///
/// `OUT_DIR` is `<target>/<profile>/build/<crate>-<hash>/out`, and cargo exposes
/// no direct way to ask. Four levels up is the profile directory.
fn target_dir() -> Option<PathBuf> {
    let out = PathBuf::from(std::env::var("OUT_DIR").ok()?);
    let profile = out.ancestors().nth(3)?.to_path_buf();
    profile.is_dir().then_some(profile)
}

